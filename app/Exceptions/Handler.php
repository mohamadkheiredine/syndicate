<?php

namespace App\Exceptions;

use App\Traits\HasValidationErrors;
use Illuminate\Database\Eloquent\ModelNotFoundException;
use Illuminate\Foundation\Exceptions\Handler as ExceptionHandler;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\HttpKernel\Exception\NotFoundHttpException;
use Symfony\Component\HttpKernel\Exception\UnauthorizedHttpException;
use Throwable;

class Handler extends ExceptionHandler
{
    use HasValidationErrors;

    /**
     * A list of exception types with their corresponding custom log levels.
     *
     * @var array<class-string<\Throwable>, \Psr\Log\LogLevel::*>
     */
    protected $levels = [
        //
    ];

    /**
     * A list of the exception types that are not reported.
     *
     * @var array<int, class-string<\Throwable>>
     */
    protected $dontReport = [
        //
    ];

    /**
     * A list of the inputs that are never flashed for validation exceptions.
     *
     * @var array<int, string>
     */
    protected $dontFlash = [
        'current_password',
        'password',
        'password_confirmation',
    ];

    /**
     * Register the exception handling callbacks for the application.
     *
     * @return void
     */
    public function register()
    {
        $this->reportable(function (Throwable $e) {
            //
        });

        $this->renderable(function (Throwable $e, $request) {
            if ($e instanceof NotFoundHttpException) {
                $previous = $e->getPrevious();
                if ($previous instanceof ModelNotFoundException) {
                    $error = $this->getBaseErrorStructure(Response::HTTP_NOT_FOUND, 'The resource was not found!');
                    return response()->json($error)->setStatusCode(Response::HTTP_NOT_FOUND);
                }
            }

            if ($e instanceof UnauthorizedHttpException) {
                abort(403);
            }
        });
    }
}
